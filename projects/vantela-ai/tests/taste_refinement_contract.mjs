import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const html=readFileSync(resolve(root,'index.html'),'utf8');
const cards=html.slice(html.indexOf('<!-- 2 · Four color blocks'),html.indexOf('<!-- 3'));
const colors=[...cards.matchAll(/flex:1 1 240px;min-width:0;background:(#[A-F0-9]+);color:/g)].map(m=>m[1]);
assert.deepEqual(colors,['#006BE0','#03DDB3','#F15A24','#F6BC17']);
const motif=label=>html.match(new RegExp('<div aria-hidden="true"[^\\n]*data-replaces="'+label+'"[^\\n]*'))?.[0];
assert(motif('hero cyan circle').includes('fill-rule="evenodd"'));
assert(motif('hero yellow triangle').includes('width:112px;height:112px'));
assert(motif('hero orange ring').includes('fill="#F6BC17"'));
assert(motif('capabilities orange ring').includes('width:200px;height:200px'));
assert(motif('capabilities orange ring').includes('fill-rule="evenodd"'));
assert(motif('capabilities yellow circle').includes('fill="#F15A24"'));
assert(!html.includes('data-replaces="capabilities cyan circle"'));
assert(!html.includes('data-replaces="stories cyan circle"'));
assert.equal((html.match(/class="vantela-boundary-cluster"/g)||[]).length,1);
assert.equal((html.match(/padding:clamp\(12px,2\.1vw,28px\)/g)||[]).length,7);
assert.equal((html.match(/role="tab" id="ve-tab-/g)||[]).length,4);
assert(html.includes('role="tabpanel" aria-labelledby="ve-tab-create"'));
assert(html.includes('prefers-reduced-motion:reduce'));
assert(html.includes("key==='ai04'?'preview-white.mp4'"));
assert(existsSync(resolve(root,'assets/animations/ai04/preview-white.mp4')));
assert(existsSync(resolve(root,'assets/animations/ai04/preview.mp4')));
assert(existsSync(resolve(root,'assets/animations/ai04/preview-web.mp4')));
const script=html.match(/<script id="vantela-explorer-interaction">([\s\S]*?)<\/script>/)?.[1];
assert(script); new Function(script);
assert(script.includes("e.key==='ArrowRight'")&&script.includes("e.key==='Home'")&&script.includes("e.key==='End'"));
console.log('PASS: card order, solid motifs, pie slices, boundary cluster, 7 insets, 4 accessible explorer tabs, original and white-preview assets, interaction syntax.');
