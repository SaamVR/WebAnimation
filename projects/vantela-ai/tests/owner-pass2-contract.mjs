import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const html=readFileSync(resolve(root,'index.html'),'utf8'),css=readFileSync(resolve(root,'owner-pass2.css'),'utf8'),js=readFileSync(resolve(root,'workflow-panel.js'),'utf8');
assert(html.includes('background:#F15A24;color:#FFFFFF;padding:32px'));
assert(!html.includes('01 / 04</span>'));
assert(html.includes('data-replaces="hero orange ring"')&&html.includes('fill="#03DDB3"'));
for(const id of ['hero','caps','services'])assert(html.match(new RegExp('id="'+id+'" style="[^"]*overflow:visible')));
for(const cls of ['vp2-story-cluster','vp2-service-ring','vp2-service-chart','vp2-service-gear','vp2-six-orbit','vp2-six-spark','vp2-document-frame'])assert(html.includes('class="vp2-ornament '+cls+'"')||html.includes('class="'+cls+'"'));
assert.equal((html.match(/data-source="/g)||[]).length,3);
assert.equal((html.match(/data-step="/g)||[]).length,4);
assert(!html.includes('class="vantela-explorer"'));
assert(html.includes('src="workflow-panel.js"'));
assert(css.includes('overflow-x:clip')&&css.includes('prefers-reduced-motion:reduce'));
assert(existsSync(resolve(root,'assets/animations/ai04/preview-white.mp4')));
