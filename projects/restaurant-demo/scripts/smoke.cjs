/* Browser smoke suite. Run with: npm install && npm run test:smoke (serve site on port 8765 first). */
const assert = require('node:assert/strict');
const puppeteer = require(process.env.PUPPETEER_MODULE || 'puppeteer');
const fs = require('node:fs');
const path = require('node:path');
const BASE = process.env.BASE_URL || 'http://127.0.0.1:8765';
const OUTPUT=process.env.QA_OUTPUT || path.join(__dirname,'..','qa-output');
(async()=>{
 fs.mkdirSync(OUTPUT,{recursive:true});
 const executablePath = process.env.CHROME_PATH || undefined;
 const browser=await puppeteer.launch({headless:true,executablePath,args:['--no-sandbox']});
 const page=await browser.newPage();
 const pageErrors=[],responseProblems=[];
 page.on('pageerror',e=>pageErrors.push(e.message));
 page.on('response',r=>{if(r.status()>=400)responseProblems.push(r.status()+' '+r.url());});
 const details={url:BASE,checks:[],warnings:[]};
 const pass=x=>details.checks.push('PASS '+x);
 try{
   await page.setViewport({width:1440,height:900,deviceScaleFactor:1});
   await page.goto(BASE,{waitUntil:'domcontentloaded',timeout:40000});
   await page.waitForSelector('.food-card');
   assert.equal(await page.$$eval('.food-card',cards=>cards.length),9);pass('Nine menu dishes render');
   await page.evaluate(()=>document.querySelectorAll('img[loading="lazy"]').forEach(img=>img.loading='eager'));
   await page.waitForFunction(()=>[...document.images].every(img=>img.complete),{timeout:15000});
   const imageFailures=await page.evaluate(()=>[...document.images].filter(img=>img.naturalWidth===0).map(img=>img.src));
   assert.equal(imageFailures.length,0,'Failed images: '+imageFailures.join(', '));pass('All real food photographs load');
   for(const name of ['f01','f02','f06-1']){await page.$eval('[data-lottie="'+name+'"]',node=>node.scrollIntoView({block:'center'}));await new Promise(resolve=>setTimeout(resolve,750));}
   await page.waitForFunction(()=>['f01','f02','f06-1'].every(name=>document.querySelector('[data-lottie="'+name+'"]').dataset.motionStatus==='loaded'),{timeout:15000});pass('F01, F02 and F06-1 original Lotties render');
   await page.evaluate(()=>window.scrollTo(0,0));
   await page.screenshot({path:path.join(OUTPUT,'desktop-home.png'),fullPage:false});
   await page.click('button[data-filter="Mains"]');
   assert.equal(await page.$$eval('.food-card',cards=>cards.length),3);pass('Main-course filter shows three dishes');
   await page.click('.food-card .add-button');
   assert.equal(await page.$eval('#cart-count',el=>el.textContent.trim()),'1');pass('Add to cart increments order');
   await page.click('#open-cart');
   await page.waitForSelector('#cart-drawer.open');
   assert.equal(await page.$eval('.cart-row h3',el=>el.textContent.trim()),'Basil Pomodoro');pass('Cart reflects selected dish');
   await new Promise(resolve=>setTimeout(resolve,550));
   await page.click('#checkout-open');
   await page.waitForSelector('#checkout-modal.open');
   await page.type('#checkout-name','Taylor');
   await page.click('#checkout-form button[type=submit]');
   await page.waitForSelector('#confirm-modal.open');
   await page.waitForFunction(()=>document.querySelector('#confirm-lottie').dataset.motionStatus==='loaded',{timeout:15000});pass('F04 order-confirmation Lottie renders');
   assert.match(await page.$eval('#confirm-message',el=>el.textContent),/No food or payment/);pass('Checkout creates simulation-only confirmation');
   await page.click('#confirm-modal [data-close]');
   await new Promise(resolve=>setTimeout(resolve,350));
   await page.type('#res-name','Taylor');
   await page.select('#res-time','6:30 PM');
   const validity=await page.$eval('#reservation-form',f=>({valid:f.checkValidity(),date:f.querySelector('#res-date').value,name:f.querySelector('#res-name').value,time:f.querySelector('#res-time').value}));
   assert.ok(validity.valid,'Reservation form invalid: '+JSON.stringify(validity));
   await page.click('#reservation-form button[type=submit]');
   await page.waitForSelector('#confirm-modal.open');
   assert.match(await page.$eval('#confirm-message',el=>el.textContent),/No real reservation/);pass('Reservation confirms demo without booking');
   await page.click('#confirm-modal [data-close]');
   await page.click('#open-book-demo');
   await page.waitForSelector('#book-modal.open');
   pass('Animated menu preview modal opens');
   await page.screenshot({path:path.join(OUTPUT,'desktop-menu-modal.png'),fullPage:false});
   await page.click('#book-modal [data-close]');
   await page.setViewport({width:390,height:844,deviceScaleFactor:1});
   await page.goto(BASE,{waitUntil:'domcontentloaded'});
   await page.waitForSelector('.food-card');
   const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth);
   assert.ok(overflow<=2,'horizontal overflow '+overflow+'px');pass('390px viewport has no horizontal overflow');
   await page.click('#mobile-menu');
   assert.equal(await page.$eval('#mobile-menu',el=>el.getAttribute('aria-expanded')),'true');pass('Mobile nav toggles');
   await page.click('#nav-links a[href="#menu"]');
   assert.equal(await page.$eval('#mobile-menu',el=>el.getAttribute('aria-expanded')),'false');pass('Mobile nav closes on selection');
   await page.screenshot({path:path.join(OUTPUT,'mobile-home.png'),fullPage:false});
   if(pageErrors.length)throw Error('Runtime JS errors: '+pageErrors.join('; '));
   pass('No JavaScript page exceptions');
   details.warnings=[...new Set(responseProblems)].filter(x=>/lottie|.json|.html/.test(x));
   fs.writeFileSync(path.join(OUTPUT,'smoke-results.json'),JSON.stringify(details,null,2));
   console.log(JSON.stringify(details,null,2));
 }catch(error){
   details.error=String(error.stack||error);
   details.warnings=responseProblems;
   fs.writeFileSync(path.join(OUTPUT,'smoke-results.json'),JSON.stringify(details,null,2));
   console.error(JSON.stringify(details,null,2));
   process.exitCode=1;
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
